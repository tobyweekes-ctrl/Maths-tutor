A, B, C = M([1, 1]), M([5, 3]), M([3, 7]); eqv('P11.4-12', [mag(B - A)**2, mag(C - B)**2, mag(C - A)**2], [20, 20, 40])
eqv('P11.4-13', M([1, 2]) + M([6, 7]) - M([4, 3]), [3, 6]); eqv('P11.4-14', 2*M([7, -2]) - M([3, 1]), [11, -5])
A, B, C = M([2, 1]), M([8, 9]), M([1, 8]); Mi = (A + B)/2; eqv('P11.4-15', [*(B - A), mag(B - A), *Mi, mag(A - C)**2, mag(B - C)**2, mag(Mi - C), mag(B - A)*mag(Mi - C)/2], [6, 8, 10, 5, 5, 50, 50, 5, 25])

# 11.5 (as [coefficient of a, coefficient of b])
eqv('P11.5-6', [1 - Q(3, 4), Q(3, 4)], [Q(1, 4), Q(3, 4)]); eqv('P11.5-8', [Q(1, 2)*Q(2, 3), Q(1, 2)], [Q(1, 3), Q(1, 2)])
