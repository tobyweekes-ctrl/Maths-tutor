eqv('P11.4-8', [*(M([4, 1]) + M([1, 3])), *((M([4, 1]) + M([1, 3]))/2)], [5, 4, Q(5, 2), 2]); eqv('P11.4-9', sorted(solve(9 + (1 - k_)**2 - 25)), [-3, 5])
