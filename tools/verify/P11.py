# Pure Year 1, Chapter 11: vectors. Vectors as sympy Matrices; symbolic a, b as coefficient pairs.
import math
from sympy import Matrix as M, Rational as Q, sqrt, solve, symbols, atan, deg, simplify, nsimplify
s_, t_, k_, p_, q_, l_ = symbols('s t k p q l')
def eqv(qid, got, want): exact(qid, sum((g - w)**2 for g, w in zip(got, want)), 0)
mag = lambda v: sqrt(sum(c**2 for c in v))
ang = lambda v: math.degrees(math.atan2(float(v[1]), float(v[0])))

# 11.1 (coefficients of a and b written as [ca, cb])
a, b = M([2, 3]), M([-1, 4]); eqv('P11.1-1', a + b, [1, 7]); eqv('P11.1-2', 3*M([2, -1]), [6, -3]); eqv('P11.1-3', a - b, [3, -1])
eqv('P11.1-6', 2*M([1, 4]) - 3*M([2, -1]), [-4, 11]); check('P11.1-7', 2*2, 4, 0)
sol = solve([p_ + 3*q_ - 7, 2*p_ - q_], [p_, q_]); eqv('P11.1-9', [sol[p_], sol[q_]], [1, 2])
eqv('P11.1-10', [2 + 1, 1 - 3], [3, -2]); eqv('P11.1-11', [solve(2*s_ + 1 - 5)[0], solve(3 - t_ - 1)[0]], [2, 2])
eqv('P11.1-12', [1 - Q(1, 3), Q(1, 3)], [Q(2, 3), Q(1, 3)]); eqv('P11.1-13', -3*M([-1, 2]), [3, -6])
MN = [-Q(1, 2), Q(2, 3)]; OP = [Q(1, 2) + MN[0]/2, MN[1]/2]; eqv('P11.1-15', MN + OP + [OP[0] - 1, OP[1]], [-Q(1, 2), Q(2, 3), Q(1, 4), Q(1, 3), -Q(3, 4), Q(1, 3)])

# 11.2
eqv('P11.2-3', M([2, 1]) + M([1, -3]), [3, -2]); eqv('P11.2-4', 3*M([2, 1]) - 2*M([1, -3]), [4, 9]); eqv('P11.2-5', M([7, -1]) - M([2, 5]), [5, -6])
check('P11.2-6', solve(Q(-9, 6) - p_/2)[0], -3, 0); sol = solve([2*s_ + t_ - 7, s_ - t_ - 2], [s_, t_]); eqv('P11.2-7', [sol[s_], sol[t_]], [3, 1])
eqv('P11.2-8', M([3, 4]) - 2*M([1, -1]) + M([0, 5]), [1, 11]); check('P11.2-9', solve(3 + k_ + 2)[0], -5, 0)
eqv('P11.2-10', [M([4, 6]) - M([1, 2]), M([10, 14]) - M([4, 6])][1] - 2*(M([4, 6]) - M([1, 2])), [0, 0])
sol = solve([2*l_ - 3*k_ - 1, -l_ + 2*k_], [l_, k_]); eqv('P11.2-12', [sol[l_], sol[k_]], [2, 1]); eqv('P11.2-13', M([5, 2]) + M([2, 4]) - M([1, 1]), [6, 5])
eqv('P11.2-14', -(M([2, 1]) + M([-1, 3])), [-1, -4]); P, Qv = M([2, -1]), M([1, 3]); eqv('P11.2-15', 3*P - Qv, [5, -6])
sol = solve(list(s_*P + t_*Qv - M([7, 7])), [s_, t_]); eqv('P11.2-15b', [sol[s_], sol[t_]], [2, 3]); eqv('P11.2-15c', P - 2*Qv, [0, -7])

# 11.3
check('P11.3', [mag([5, 12]), mag([-6, 8]), mag([4, 3])], [13, 10, 5], 0); exact('P11.3-4', mag([2, -3]), sqrt(13)); check('P11.3-4b', ang([2, -3]), -56.3, 0.06)
check('P11.3-angles', [ang([4, 4]), ang([2, 5]), ang([-2, 5])], [45, 68.2, 111.8], 0.06); eqv('P11.3-7', 10*M([3, -4])/5, [6, -8]); eqv('P11.3-9', 26*M([5, -12])/13, [10, -24])
eqv('P11.3-10', sorted(solve(5*k_**2 - 100)), [-2*sqrt(5), 2*sqrt(5)]); check('P11.3-11', mag(M([3, 1]) + M([1, 2])), 5, 0)
eqv('P11.3-12', [8*sqrt(3)/2, 8*Q(1, 2)], [4*sqrt(3), 4]); eqv('P11.3-13', sorted(solve(p_**2 + (p_ + 1)**2 - 25)), [-4, 3])
