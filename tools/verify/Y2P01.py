check('2P1.3-12b', sorted(float(s) for s in sp.solve((4*x + 5)/((2*x + 1)*(x + 2)) - 1, x)), [-1.5, 1], 1e-12)
check('2P1.3-14', sum(Fr(2, k*(k + 2)) for k in range(1, 5)), 17/15, 1e-12)
