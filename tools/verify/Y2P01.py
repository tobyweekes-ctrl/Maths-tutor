# Pure Year 2, Chapter 1: algebraic methods. Fractions are checked with sympy (apart, cancel).
import sympy as sp
from fractions import Fraction as Fr
x, r, n = sp.symbols('x r n')
eq = lambda q, a, b: exact(q, sp.simplify(a - b), 0)
# 1.1: the numerical facts the proofs rely on
check('2P1.1-5', all((k*k) % 2 == 1 for k in range(1, 400, 2)), True, 0)
check('2P1.1-6', all((2*a + 4*b) % 2 == 0 for a in range(-20, 20) for b in range(-20, 20)), True, 0)
check('2P1.1-8-9', [sp.sqrt(2).is_rational, sp.sqrt(3).is_rational], [False, False], 0)
check('2P1.1-10', [sp.isprime(30031), 59*509], [False, 30031], 0)
check('2P1.1-11', any(a*a - 4*b == 2 for a in range(-40, 40) for b in range(-400, 400)), False, 0)
check('2P1.1-12', min(t + 1/t for t in [i/100 for i in range(1, 1000)]) >= 2 - 1e-12, True, 0)
check('2P1.1-14', any(2**a == 3**b for a in range(1, 60) for b in range(1, 40)), False, 0)
check('2P1.1-15', [(a, b) for a in range(1, 200) for b in range(1, 200) if a*a - b*b == 1], [], 0)
# 1.2
eq('2P1.2-1', (x**2 - 9)/(x + 3), x - 3); eq('2P1.2-2', (2*x**2 + 6*x)/(4*x), (x + 3)/2); eq('2P1.2-3', 3/x*x**2/6, x/2)
eq('2P1.2-4', (x**2 + 5*x + 6)/(x**2 - 4), (x + 3)/(x - 2)); eq('2P1.2-5', 1/(x + 1) + 2/(x - 1), (3*x + 1)/((x + 1)*(x - 1)))
eq('2P1.2-6', (x**2 - 1)/(x + 2) / ((x + 1)/(x**2 + 2*x)), x*(x - 1)); eq('2P1.2-7', 3/(x - 2) - 1/x, 2*(x + 1)/(x*(x - 2)))
eq('2P1.2-8', (2*x**2 - x - 3)/(x**2 - 1), (2*x - 3)/(x - 1)); eq('2P1.2-9', x/(x + 2) + 4/(x**2 - 4), (x**2 - 2*x + 4)/(x**2 - 4))
check('2P1.2-10', sorted(float(s) for s in sp.solve(2/(x + 1) + 1/(x - 2) - 1, x)), sorted([2 - 3**0.5, 2 + 3**0.5]), 1e-9)
eq('2P1.2-11', (x**3 - 8)/(x**2 - 4), (x**2 + 2*x + 4)/(x + 2)); eq('2P1.2-12', (x + 4)/(x**2 - x - 2) - 2/(x - 2), -1/(x + 1))
eq('2P1.2-13', 1 - 3/(x + 2) + 3/(x + 2)**2, (x**2 + x + 1)/(x + 2)**2)
y = sp.symbols('y'); eq('2P1.2-14', (1/x - 1/y)/(x - y), -1/(x*y))
f = (4*x**2 - 9)/(2*x**2 + x - 3); eq('2P1.2-15', f, (2*x - 3)/(x - 1)); check('2P1.2-15b', [float(s) for s in sp.solve(f - 3, x)], [0], 1e-12)
