def qroots(a, b, c): d = math.sqrt(b*b - 4*a*c); return sorted([(-b - d)/(2*a), (-b + d)/(2*a)])
def varea(pts):   # signed area under a piecewise-linear graph
    return sum((t2 - t1)*(v1 + v2)/2 for (t1, v1), (t2, v2) in zip(pts, pts[1:]))
def vdist(pts):   # total distance (splits segments that cross the axis)
    tot = 0
    for (t1, v1), (t2, v2) in zip(pts, pts[1:]):
        if v1*v2 < 0: tc = t1 + v1/(v1 - v2)*(t2 - t1); tot += abs(v1)*(tc - t1)/2 + abs(v2)*(t2 - tc)/2
        else: tot += abs((t2 - t1)*(v1 + v2)/2)
    return tot
